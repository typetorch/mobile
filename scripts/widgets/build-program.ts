/**
 * Builds the widget program (docs/WIDGET_PROGRAM.md): bundles src/features/live/widgets/program/ with bun build into
 * one self-contained script that defines the global functions plan, shape and tap, and writes it as a string to
 * src/features/live/widgets/program.generated.ts (`WIDGET_PROGRAM`, committed; LiveSync sends it with
 * setWidgetProgram). Hermes compiles app functions to bytecode, so the source must be a string made here.
 *
 * Run: `timeout 60 bun scripts/widgets/build-program.ts`
 *   --check  exit 1 when program.generated.ts isn't what a build makes now (nothing written)
 */

// Bun's API (run with bun; the app's tsconfig has no bun types, so just what is used here).
type BunOutput = { text(): Promise<string> };
declare const Bun: {
	build(o: {
		entrypoints: string[];
		target: "browser";
		format: "esm";
		minify: { whitespace: boolean; syntax: boolean; identifiers: boolean };
	}): Promise<{ success: boolean; logs: unknown[]; outputs: BunOutput[] }>;
	file(path: string): { text(): Promise<string>; exists(): Promise<boolean> };
	write(path: string, data: string): Promise<number>;
	argv: string[];
};
declare const process: { exit(code?: number): never };

export const ENTRY = new URL("../../src/features/live/widgets/program/index.ts", import.meta.url).pathname;
export const GENERATED = new URL("../../src/features/live/widgets/program.generated.ts", import.meta.url).pathname;

/** The functions the native side calls. */
const NAMES = ["plan", "shape", "tap"];

/** Syntax newer than ES2020 that bun build leaves as written (the sandbox's V8 is new, but the doc promises ES2020). */
const NEWER_SYNTAX: [RegExp, string][] = [
	[/\?\?=|\|\|=|&&=/, "logical assignment (ES2021)"],
	[/\b\d+_\d/, "numeric separator (ES2021)"],
	[/\.at\(/, "Array/String .at() (ES2022)"],
	[/\.replaceAll\(/, "replaceAll (ES2021)"],
	[/Object\.hasOwn\(/, "Object.hasOwn (ES2022)"],
	[/\bstatic\s*\{/, "class static block (ES2022)"],
	[/#[A-Za-z_$][\w$]*\s*(=|;|\()/, "private class member (ES2022)"],
];

/** The program's source: the bundle in a function scope, then the three global functions calling into it. */
export async function buildProgram(): Promise<string> {
	const result = await Bun.build({
		entrypoints: [ENTRY],
		target: "browser",
		format: "esm",
		// Names kept: an error's first line is drawn on the widget and logged.
		minify: { whitespace: true, syntax: true, identifiers: false },
	});
	if (!result.success || result.outputs.length !== 1) {
		throw new Error(`bun build failed:\n${result.logs.map(String).join("\n")}`);
	}
	let code = (await result.outputs[0].text()).trim();
	if (/^\s*import[\s{*"']/m.test(code)) throw new Error("the bundle still imports something");
	// The bundle ends with `export{a as plan,…};`: take the local names, drop the statement.
	const m = /export\s*\{([^}]*)\};?\s*$/.exec(code);
	if (!m) throw new Error("no export statement at the end of the bundle");
	code = code.slice(0, m.index).trim();
	const locals: Record<string, string> = {};
	for (const part of m[1].split(",")) {
		const p = part.trim();
		if (!p) continue;
		const [local, exported] = p.split(/\s+as\s+/).map((s) => s.trim());
		locals[exported ?? local] = local;
	}
	for (const name of NAMES) if (!locals[name]) throw new Error(`the program doesn't export ${name}`);
	for (const [re, what] of NEWER_SYNTAX) if (re.test(code)) throw new Error(`the bundle uses ${what}: ${re}`);
	const ret = NAMES.map((n) => `${n}:${locals[n]}`).join(",");
	return [
		"// TypeTorch widget program (docs/WIDGET_PROGRAM.md). Built from src/features/live/widgets/program/.",
		`var __ttProgram=(function(){"use strict";${code}\nreturn{${ret}};})();`,
		...NAMES.map((n) => `function ${n}(input){return __ttProgram.${n}(input);}`),
		"",
	].join("\n");
}

export function generatedFile(source: string): string {
	return `/**
 * The widget program as one script (docs/WIDGET_PROGRAM.md), sent by LiveSync with setWidgetProgram.
 * Generated by scripts/widgets/build-program.ts from src/features/live/widgets/program/: don't edit, run
 * \`timeout 60 bun scripts/widgets/build-program.ts\` after a change there.
 */
export const WIDGET_PROGRAM: string = ${JSON.stringify(source)};
`;
}

if ((import.meta as { main?: boolean }).main) {
	const source = await buildProgram();
	const out = generatedFile(source);
	const file = Bun.file(GENERATED);
	const current = (await file.exists()) ? await file.text() : "";
	if (Bun.argv.includes("--check")) {
		if (current !== out) {
			console.error("✗ program.generated.ts is out of date: run `timeout 60 bun scripts/widgets/build-program.ts`");
			process.exit(1);
		}
		console.log(`✓ program.generated.ts is current (${source.length} chars)`);
		process.exit(0);
	}
	if (current === out) console.log(`program.generated.ts unchanged (${source.length} chars)`);
	else {
		await Bun.write(GENERATED, out);
		console.log(`wrote ${GENERATED} (${source.length} chars)`);
	}
}
